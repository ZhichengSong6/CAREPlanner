#!/usr/bin/env python3
"""Fresh 4-GPU promotion holdout for V1 vs E1 vs R1.

Only validation x-indices never used by the completed 1388-case development
benchmark are eligible. Starts are generated by the analytic FOV oracle before
model evaluation, persisted with SHA256, then sharded across four GPUs.
"""
from __future__ import annotations
import argparse
from collections import Counter, defaultdict
from datetime import timedelta
import hashlib, json, math, os
from pathlib import Path
import sys, time
import numpy as np
import torch
import torch.distributed as dist

HERE=Path(__file__).resolve().parent
REPO=HERE.parents[1]
E012_DIR=REPO/'experiments/hierarchical9_e012_end2end_v1'
ABC_DIR=REPO/'experiments/hierarchical9_abc_capacity_routing_v1'
for p in (str(E012_DIR),str(ABC_DIR),str(HERE)):
    if p not in sys.path: sys.path.insert(0,p)
import e012_protocol as eproto
base=eproto._load('r012_fresh_base',HERE/'evaluate_unified.py')
old=eproto.old
NAMES=('V1','E1','R1')
SEED=20260921
MAX_FRESH_X_PER_SENSOR=16
LOCAL_RADII=(.01,.02,.05)
UNIFORM_PER_X=10

def log(*x):
    if not dist.is_initialized() or dist.get_rank()==0: print(*x,flush=True)

def fraction(k,n):
    return {'passed':int(k),'count':int(n),'rate':float(k/n) if n else None}

def exact_sign_p(a,b):
    n=a+b
    if not n: return 1.0
    k=min(a,b)
    return min(1.0,2*sum(math.comb(n,i) for i in range(k+1))/(2**n))

def aggregate(rows):
    out={}
    for cohort,chosen in (
        ('local',[r for r in rows if '/local_' in r['group']]),
        ('uniform',[r for r in rows if r['group'].endswith('uniform_outside')]),
        ('all',rows)):
        out[cohort]={n:fraction(sum(r['models'][n]['fov_pass'] for r in chosen),len(chosen)) for n in NAMES}
    return out

def per_sensor(rows):
    out={}
    for s in range(8):
        chosen=[r for r in rows if r['sensor']==s]
        out[f'S{s}']={n:fraction(sum(r['models'][n]['fov_pass'] for r in chosen),len(chosen)) for n in NAMES}
    return out

def failures(rows,name):
    rr=[r['models'][name] for r in rows]
    return {'failure_stages':dict(Counter(r['failure_stage'] for r in rr)),
            'root_source_by_failure':dict(Counter(r['root_source']+' / '+r['failure_stage'] for r in rr))}

def paired(rows,a,b):
    c=Counter()
    for r in rows:
        av=bool(r['models'][a]['fov_pass']); bv=bool(r['models'][b]['fov_pass'])
        c['both_pass' if av and bv else a+'_only' if av else b+'_only' if bv else 'both_fail'] += 1
    ao,bo=c[a+'_only'],c[b+'_only']
    return {**dict(c),'net_'+a+'_minus_'+b:ao-bo,'exact_sign_p':exact_sign_p(ao,bo)}

def markdown(r):
    f=lambda v:'N/A' if v is None else f'{v:.5f}'
    lines=['# Fresh promotion holdout: V1 vs E1 vs R1','',
        f"Fresh seed: {r['fresh_seed']}; fresh x/sensor: {r['fresh_x_per_sensor']}; development-used x excluded: {r['excluded_development_x_count']}.",
        f"Starts SHA256: {r['starts_sha256']}. Starts were fixed before model evaluation.",'',
        '## Aggregate','','| Cohort | N | V1 | E1 | R1 |','|---|---:|---:|---:|---:|']
    for c in ('local','uniform','all'):
        row=r['aggregate'][c]; lines.append(f"| {c} | {row['V1']['count']} | {f(row['V1']['rate'])} | {f(row['E1']['rate'])} | {f(row['R1']['rate'])} |")
    lines += ['','## Paired outcomes','','| Pair | A-only | B-only | Net A-B | exact sign p |','|---|---:|---:|---:|---:|']
    for key,a,b in (('R1_vs_V1','R1','V1'),('R1_vs_E1','R1','E1'),('E1_vs_V1','E1','V1')):
        x=r['paired'][key]; lines.append(f"| {a} vs {b} | {x.get(a+'_only',0)} | {x.get(b+'_only',0)} | {x['net_'+a+'_minus_'+b]} | {x['exact_sign_p']:.6f} |")
    lines += ['','## Failure stages','','| Model | ROOT_NOT_FOUND | CANDIDATE_BUT_FOV_FAIL | SUCCESS |','|---|---:|---:|---:|']
    for n in NAMES:
        c=r['failures'][n]['failure_stages']
        lines.append(f"| {n} | {c.get('ROOT_NOT_FOUND',0)} | {c.get('LEARNED_CANDIDATE_BUT_FOV_FAIL',0)} | {c.get('SUCCESS',0)} |")
    lines += ['','## Per sensor','']
    for s in range(8):
        row=r['per_sensor'][f'S{s}']; lines += [f"### S{s} (N={row['V1']['count']})",'','| Model | FOV pass |','|---|---:|']
        for n in NAMES: lines.append(f"| {n} | {f(row[n]['rate'])} |")
        lines.append('')
    return '\n'.join(lines)+'\n'

def build_starts(cache,dataset,oracle,core,device,used_x):
    d=cache.arrays['val']; rng=np.random.default_rng(SEED)
    pools={}
    for s in range(8):
        pool=np.unique(d['x_index'][d['s']==s])
        pools[s]=np.asarray([int(x) for x in pool if int(x) not in used_x],dtype=np.int64)
    fresh_x=min(MAX_FRESH_X_PER_SENSOR,min(len(v) for v in pools.values()))
    if fresh_x<12: raise RuntimeError(f'Only {fresh_x} fully unused x/sensor remain; too small for spatial holdout')
    starts=[]; selected={}; excluded=Counter()
    lo,hi=dataset.q_limits(device)
    for s in range(8):
        pts=np.sort(rng.choice(pools[s],fresh_x,replace=False)); selected[f'S{s}']=[int(v) for v in pts]
        for xi in pts:
            for kind in (0,1):
                ii=np.flatnonzero((d['s']==s)&(d['x_index']==xi)&(d['kind']==kind))
                if not len(ii): excluded[f'S{s}/missing_kind{kind}']+=1; continue
                i=int(ii[0]); x=torch.tensor(d['x'][i],device=device)
                for radius in LOCAL_RADII:
                    qout=torch.tensor(d['q'][i]-radius*d['normal'][i],device=device)
                    qin=torch.tensor(d['q'][i]+radius*d['normal'][i],device=device)
                    group=f'S{s}/local_kind{kind}_r{radius}'
                    if (not core.within(qout,lo,hi) or not core.within(qin,lo,hi) or
                        oracle.value(x,qout,s)>=-1e-5 or oracle.value(x,qin,s)<=1e-5):
                        excluded[group]+=1; continue
                    starts.append({'group':group,'x_index':int(xi),'sensor':s,'x':x.tolist(),'q_init':qout.tolist()})
            x=dataset.x_cpu[int(xi)].to(device)
            for _ in range(UNIFORM_PER_X):
                found=None
                for _try in range(64):
                    q=torch.tensor(rng.uniform(cache.lo,cache.hi),device=device,dtype=torch.float32)
                    if oracle.value(x,q,s)<0: found=q; break
                if found is None: excluded[f'S{s}/uniform_no_outside_after_64']+=1; continue
                starts.append({'group':f'S{s}/uniform_outside','x_index':int(xi),'sensor':s,'x':x.tolist(),'q_init':found.tolist()})
    if any(int(r['x_index']) in used_x for r in starts): raise AssertionError('development x leakage')
    return fresh_x,starts,selected,dict(excluded)

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--r012-root',type=Path,required=True); ap.add_argument('--reference-root',type=Path,required=True); args=ap.parse_args()
    if not torch.cuda.is_available() or 'LOCAL_RANK' not in os.environ: raise RuntimeError('Launch with torchrun --nproc_per_node=4')
    local_rank=int(os.environ['LOCAL_RANK']); torch.cuda.set_device(local_rank); device=torch.device('cuda',local_rank)
    dist.init_process_group('nccl',timeout=timedelta(minutes=60))
    try:
        if dist.get_world_size()!=4: raise RuntimeError(f'Fresh holdout requires 4 GPUs, got {dist.get_world_size()}')
        rank=dist.get_rank(); torch.set_num_threads(2)
        torch.backends.cuda.matmul.allow_tf32=False; torch.backends.cudnn.allow_tf32=False
        rroot=args.r012_root.resolve(); refroot=args.reference_root.resolve()
        dev=rroot/'evaluation_unified_dev'; out=rroot/'evaluation_fresh_holdout_v1'
        cache,p0,p0_sha=eproto.load_reference_root(refroot); artifact=Path(p0['args']['artifact_root'])
        models={}
        v1,_=old.load_v1(artifact/old.V1_REL,device); models['V1']=v1.eval().requires_grad_(False)
        ecp,edigest=eproto.load_checkpoint(eproto.output_dir(refroot,'E1','pilot')/'final.pt')
        eproto.assert_checkpoint(ecp,p0,p0_sha,cache.identity,require_pilot=True)
        models['E1']=eproto.load_model_from_checkpoint(ecp,p0,device).requires_grad_(False)
        rcp,rrun,rdigest=base.load_r_checkpoint(rroot,'R1'); models['R1']=base.load_r_model(rcp,'R1',device)
        ev=old.module('evaluate_pair',eproto.abc.p2.LEGACY)
        stats=old.module('evaluate_p2',eproto.abc.P2_DIR)
        api=old.module('train_signed_visibility_cdf_pairwise_replace',old.SCRIPTS)
        dataset=api.VisibilityQ0Dataset(str(artifact/old.DATA_REL),1000,0); cache.verify_dataset(dataset,artifact/old.DATA_REL)
        oracle=old.module('oracle',old.AUDIT).SensorOracle(old.URDF,device,api.DEFAULT_JOINT_NAMES,api.DEFAULT_SENSOR_FRAMES)
        core=old.module('core',old.AUDIT); probeapi=old.module('runtime_probe',old.AUDIT)
        lo,hi=dataset.q_limits(device)
        probes={n:probeapi.make_probe(ev.SensorView(m),dataset.sensor_masks(device),lo,hi) for n,m in models.items()}
        old.module('audit',old.AUDIT).preflight(dataset,oracle,probes,device)

        if rank==0:
            if out.exists(): raise FileExistsError(f'No overwrite: {out}')
            dm=json.loads((dev/'manifest.json').read_text())
            if dm.get('status')!='COMPLETE': raise ValueError('Development eval must be COMPLETE')
            dev_rows=[json.loads(line) for line in (dev/'solves.jsonl').read_text().splitlines() if line.strip()]
            if len(dev_rows)!=1388: raise ValueError(f'Expected 1388 development solves, got {len(dev_rows)}')
            used_x={int(r['x_index']) for r in dev_rows}
            fresh_x,starts,selection,excluded=build_starts(cache,dataset,oracle,core,device,used_x)
            out.mkdir(parents=True)
            start_text=''.join(json.dumps(r,sort_keys=True,separators=(',',':'))+'\n' for r in starts)
            starts_sha=hashlib.sha256(start_text.encode()).hexdigest(); (out/'starts.jsonl').write_text(start_text)
            local=sum('/local_' in r['group'] for r in starts); uniform=sum(r['group'].endswith('uniform_outside') for r in starts)
            if len(starts)<1600 or local<500 or uniform<1000: raise RuntimeError(f'Holdout too small: total={len(starts)} local={local} uniform={uniform}')
            manifest={'status':'RUNNING','evaluation':'fresh_promotion_holdout_v1','models':list(NAMES),'world_size':4,
                'fresh_seed':SEED,'fresh_x_per_sensor':fresh_x,'development_solve_count':len(dev_rows),
                'excluded_development_x_count':len(used_x),'starts_sha256':starts_sha,'start_count':len(starts),
                'local_count':local,'uniform_count':uniform,'selected_x_by_sensor':selection,'selection_exclusions':excluded,
                'checkpoint_sha256':{'V1':old.V1_SHA,'E1':edigest,'R1':rdigest},
                'limitations':'Fresh x within existing seed-0 validation dataset; FOV-only; no new data, LOS, collision, trajectory, actual-seen.'}
            base.write_json(out/'manifest.json',manifest)
            log(f'[fresh] x/sensor={fresh_x} starts={len(starts)} local={local} uniform={uniform} excluded_dev_x={len(used_x)} sha={starts_sha}')
        dist.barrier()
        starts=[json.loads(x) for x in (out/'starts.jsonl').read_text().splitlines() if x.strip()]
        t0=time.perf_counter(); rank_path=out/f'solves.rank{rank}.jsonl'
        with rank_path.open('w') as fs:
            for i in range(rank,len(starts),4):
                spec=starts[i]; x=torch.tensor(spec['x'],device=device,dtype=torch.float32); q=torch.tensor(spec['q_init'],device=device,dtype=torch.float32); s=int(spec['sensor'])
                row={**spec,'case_id':i,'models':{}}
                order=list(NAMES[i%len(NAMES):])+list(NAMES[:i%len(NAMES)])
                for n in order: row['models'][n]=probeapi.run_probe(probes[n],oracle,x,q,s)
                fs.write(json.dumps(core.json_safe(row),allow_nan=False)+'\n'); fs.flush()
                if (i-rank)//4 and ((i-rank)//4)%100==0: print(f'[fresh rank{rank}] local_cases={(i-rank)//4}',flush=True)
        dist.barrier()
        if rank==0:
            rows=[]
            for r in range(4):
                rows += [json.loads(x) for x in (out/f'solves.rank{r}.jsonl').read_text().splitlines() if x.strip()]
            rows.sort(key=lambda x:x['case_id'])
            if len(rows)!=len(starts) or [r['case_id'] for r in rows]!=list(range(len(starts))): raise RuntimeError('shard merge mismatch')
            with (out/'solves.jsonl').open('w') as f:
                for row in rows: f.write(json.dumps(row,allow_nan=False)+'\n')
            groups=defaultdict(list)
            for row in rows: groups[row['group']].append(row)
            manifest=json.loads((out/'manifest.json').read_text())
            report={'status':'COMPLETE','fresh_seed':SEED,'fresh_x_per_sensor':manifest['fresh_x_per_sensor'],
                'starts_sha256':manifest['starts_sha256'],'excluded_development_x_count':manifest['excluded_development_x_count'],
                'aggregate':aggregate(rows),'per_sensor':per_sensor(rows),
                'failures':{n:failures(rows,n) for n in NAMES},
                'paired':{'R1_vs_V1':paired(rows,'R1','V1'),'R1_vs_E1':paired(rows,'R1','E1'),'E1_vs_V1':paired(rows,'E1','V1')},
                'groups':{k:base.solve_summary(v,list(NAMES),stats) for k,v in groups.items()},
                'elapsed_seconds':time.perf_counter()-t0}
            base.write_json(out/'report.json',report); (out/'summary.md').write_text(markdown(report),encoding='utf-8')
            manifest.update(status='COMPLETE',elapsed_seconds=report['elapsed_seconds']); base.write_json(out/'manifest.json',manifest)
            log(f'[done] fresh_promotion_holdout_complete output={out}')
        dist.barrier()
    finally:
        if dist.is_initialized(): dist.destroy_process_group()

if __name__=='__main__': main()
