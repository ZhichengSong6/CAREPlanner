"""Analytic observation backend. No learned weights or motion permission.

The analytic adapter exposes a LOCAL LINEARIZED joint margin (rad), not a
global signed C-space distance. Raw plane margins/Jacobians remain in m/m/rad.
Branch poses are generated by trust-bounded geometric LP and separately checked
by the existing FOV/self/external LOS checker. No map is updated here.
"""
import json
import math
import os
from pathlib import Path
import time
import numpy as np
import torch
from torch import nn
from validate_visibility_oracle import DEFAULT_JOINT_NAMES,DEFAULT_SENSOR_FRAMES,find_chain_joints,joint_origin_transform
from urdf_parser_py.urdf import URDF

def audit(kind,**fields):
    path=os.environ.get('CARE_BACKEND_AUDIT_FILE')
    if path:
        with open(path,'a') as f:f.write(json.dumps(dict(kind=kind,backend=os.environ.get('CARE_VISIBILITY_BACKEND','r1'),**fields))+'\n')

class AnalyticGeometry(nn.Module):
    def __init__(self,urdf):
        super().__init__();self.calls=0;self.cached={};self.chains=[]
        robot=URDF.from_xml_file(str(urdf));idx={n:i for i,n in enumerate(DEFAULT_JOINT_NAMES)}
        for frame in DEFAULT_SENSOR_FRAMES:
            row=[]
            for j in find_chain_joints(robot,'base_link',frame):
                axis=np.array(j.axis or [1,0,0],float)
                if j.type!='fixed':axis/=np.linalg.norm(axis)
                x,y,z=axis;K=np.array([[0,-z,y],[z,0,-x],[-y,x,0]])
                row.append((joint_origin_transform(j),j.type,idx.get(j.name,-1),axis,K))
            self.chains.append(row)
        ax=math.tan(math.radians(55)/2);ay=math.tan(math.radians(72)/2)
        nx=math.sqrt(1+ax*ax);ny=math.sqrt(1+ay*ay)
        self.normals=np.array([[1/nx,0,ax/nx],[-1/nx,0,ax/nx],[0,1/ny,ay/ny],[0,-1/ny,ay/ny],[0,0,1],[0,0,-1]])
        self.offsets=np.array([0,0,0,0,-.15,.75])

    def numpy_planes(self,points,q,sid):
        T=np.eye(4);D=np.zeros((7,4,4))
        for origin,typ,j,axis,K in self.chains[sid]:
            m=np.eye(4);dm=np.zeros((4,4))
            if j>=0 and typ!='fixed':
                if typ in ('revolute','continuous'):
                    c=math.cos(q[j]);s=math.sin(q[j]);aa=np.outer(axis,axis)
                    m[:3,:3]=c*np.eye(3)+(1-c)*aa+s*K;dm[:3,:3]=-s*np.eye(3)+s*aa+c*K
                elif typ=='prismatic':m[:3,3]=axis*q[j];dm[:3,3]=axis
                else:raise ValueError(typ)
            A=origin@m;D=D@A
            if j>=0 and typ!='fixed':D[j]+=T@origin@dm
            T=T@A
        diff=np.asarray(points)-T[:3,3];local=diff@T[:3,:3]
        dl=np.einsum('pi,kij->pkj',diff,D[:,:3,:3])-np.einsum('ki,ij->kj',D[:,:3,3],T[:3,:3])[None,:,:]
        return (local@self.normals.T+self.offsets).reshape(-1),np.einsum('pkj,aj->pak',dl,self.normals).reshape(-1,7)

    def _torch_planes(self,inputs,sid):
        q=inputs[:,3:];N=len(q);key=(q.device,q.dtype,sid)
        if key not in self.cached:
            tensor=lambda x:torch.as_tensor(x,device=q.device,dtype=q.dtype)
            self.cached[key]=([(tensor(o),t,j,tensor(a),tensor(k)) for o,t,j,a,k in self.chains[sid]],tensor(self.normals),tensor(self.offsets))
        chain,normals,offsets=self.cached[key]
        I=torch.eye(4,device=q.device,dtype=q.dtype);I3=I[:3,:3]
        T=I.expand(N,4,4);D=torch.zeros((N,7,4,4),device=q.device,dtype=q.dtype)
        for origin,typ,j,axis,K in chain:
            motion=I.expand(N,4,4).clone();dm=torch.zeros_like(motion)
            if j>=0 and typ!='fixed':
                if typ in ('revolute','continuous'):
                    c=torch.cos(q[:,j])[:,None,None];s=torch.sin(q[:,j])[:,None,None];aa=axis[:,None]*axis[None,:]
                    motion[:,:3,:3]=c*I3+(1-c)*aa+s*K
                    dm[:,:3,:3]=-s*I3+s*aa+c*K
                else:motion[:,:3,3]=q[:,j,None]*axis;dm[:,:3,3]=axis
            A=origin@motion;dn=D@A[:,None,:,:]
            if j>=0 and typ!='fixed':
                add=torch.zeros_like(dn);add[:,j]=T@origin@dm;dn=dn+add
            D=dn;T=T@A
        diff=inputs[:,:3]-T[:,:3,3];rotation=T[:,:3,:3]
        local=torch.einsum('ni,nij->nj',diff,rotation)
        dl=torch.einsum('ni,nkij->nkj',diff,D[:,:,:3,:3])-torch.einsum('nki,nij->nkj',D[:,:,:3,3],rotation)
        planes=local@normals.T+offsets
        jac=torch.einsum('nkj,aj->nak',dl,normals)
        return planes,jac

    def forward_sensor(self,inputs,sid):
        planes,jac=self._torch_planes(inputs,sid)
        # Local linearized configuration margin; finite cap is explicitly a
        # numerical ranking convention for immovable planes, not exact distance.
        value=planes/torch.linalg.vector_norm(jac,dim=-1).clamp(min=1e-4)
        return value.clamp(-2*math.pi,2*math.pi).min(dim=1).values

    def forward_sensors(self,inputs):
        self.calls+=1
        if self.calls==1 or self.calls%64==0:audit('analytic_forward',calls=self.calls,neural_loads=0,neural_forwards=0,value_kind='local_linearized_joint_margin_rad')
        return torch.stack([self.forward_sensor(inputs,s) for s in range(8)],dim=1)

    def forward_union(self,inputs):return self.forward_sensors(inputs).max(dim=1).values
    def forward(self,inputs):
        sensors=self.forward_sensors(inputs)
        return torch.cat([sensors.max(dim=1).values[:,None],sensors],dim=1)

