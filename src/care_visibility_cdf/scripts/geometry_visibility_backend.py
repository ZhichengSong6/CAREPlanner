def optimize_branch(runtime,points,q_start,sid):
    from scipy.optimize import linprog
    xyz=points.detach().cpu().numpy();q0=q_start[0].detach().cpu().numpy().astype(float)
    q0=np.clip(q0,runtime.q_min_np,runtime.q_max_np);q=q0.copy()
    model=runtime.model.full_model;active=np.flatnonzero(runtime.sensor_masks_np[sid]);hist=[]
    best=q.copy();best_margin=-math.inf;accepted=False;count=0
    rng=np.random.default_rng(20261105+sid)
    # Online iteration cap follows the original branch work envelope. The
    # offline2-rad trajectory-variation cap is deliberately not an online gate.
    limit=runtime.projection_iters+runtime.root_refine_iters+runtime.branch_fallback_ascent_steps
    for restart in range(3):
        q=q0.copy()
        if restart:
            d=rng.normal(size=len(active));d/=np.linalg.norm(d);q[active]+=.25*d;q=np.clip(q,runtime.q_min_np,runtime.q_max_np)
        while count<limit:
            count+=1;planes,J=model.numpy_planes(xyz,q,sid);margin=float(planes.min())
            hist.append(dict(iter=count,q=q.tolist(),score=margin,score_unit='m',phase='geometry_lp'))
            if margin>best_margin:best=q.copy();best_margin=margin
            if margin>=0:
                geo=runtime._candidate_geometry(xyz,q,sid)
                if geo['accepted']:best=q.copy();accepted=True;break
            radius=.125/math.sqrt(len(active))
            bounds=[(max(-radius,runtime.q_min_np[j]-q[j]),min(radius,runtime.q_max_np[j]-q[j])) for j in active]+[(None,None)]
            sol=linprog(np.r_[np.zeros(len(active)),-1.],A_ub=np.column_stack([-J[:,active],np.ones(len(planes))]),
                b_ub=planes,bounds=bounds,method='highs')
            if not sol.success:break
            delta=np.zeros(7);delta[active]=sol.x[:-1]
            if np.linalg.norm(delta)<1e-8:break
            moved=False
            for fraction in [1.,.5,.25,.125,.0625,.03125]:
                trial=q+delta*fraction;values,_=model.numpy_planes(xyz,trial,sid)
                if values.min()>margin+1e-9:q=trial;moved=True;break
            if not moved:break
        if accepted or count>=limit:break
    score=runtime.branch_score_numpy(xyz,best,sid)
    return dict(sensor_id=int(sid),sensor_frame=DEFAULT_SENSOR_FRAMES[sid],q_start=q0.tolist(),
        q_candidate=best.tolist(),q_zero=best.tolist(),initial_score=runtime.branch_score_numpy(xyz,q0,sid),
        best_score=score,final_score=score,f_zero=score,root_found=False,root_source='analytic_geometry',
        solution_mode='geometry_trust_lp',projection_history=hist,root_history=[],ascent_history=[],
        value_kind='local_linearized_joint_margin_rad',geometry_accepted_during_search=accepted)
